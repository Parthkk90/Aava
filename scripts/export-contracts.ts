/**
 * Exports the compiled DemoToken ABI and bytecode into a typed TS module so
 * tests and the demo do not need a Solidity toolchain.
 * Usage: (cd contracts && forge build) && pnpm tsx scripts/export-contracts.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const artifact = JSON.parse(readFileSync("contracts/out/DemoToken.sol/DemoToken.json", "utf8")) as {
  abi: unknown[];
  bytecode: { object: string };
};
const source = readFileSync("contracts/src/DemoToken.sol");
const sha = createHash("sha256").update(source).digest("hex");

const out = `// GENERATED by scripts/export-contracts.ts from contracts/src/DemoToken.sol — do not edit.
// Source sha256: ${sha}
// Compiler: solc 0.8.28, optimizer 200 runs, no metadata hash (reproducible).
export const demoTokenAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;

export const demoTokenBytecode = "${artifact.bytecode.object}" as const;
`;
writeFileSync("packages/chain/src/demo-token.ts", out);
console.log(`wrote packages/chain/src/demo-token.ts (source sha256 ${sha})`);
